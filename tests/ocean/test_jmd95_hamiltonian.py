"""Independent EOS/energy derivatives, operator work and stage acceptance."""
import pytest
import torch

from vfs.geometry.mesh import VoronoiMesh
from vfs.ocean import Ocean, OceanColumn, OceanDomain, OceanState
from vfs.ocean.eos import jmd95_seawater_density
from vfs.ocean.jmd95 import JMD95Dynamics, checked_ssprk3
from vfs.ocean.jmd95_energy import JMD95Energy, jmd95_partials
from vfs.integrators.explicit import ssprk3


@pytest.fixture(scope='module')
def mesh():
    torch.set_default_dtype(torch.float64)
    torch.set_num_threads(1)
    return VoronoiMesh(n_cells=32, lloyd_iters=2, verbose=False)


def case(mesh, coast=False):
    domain = OceanDomain(mesh, mesh.cell_xyz[:, 2] > -.4) if coast else None
    column = OceanColumn(3, total_depth=3000.)
    x, y = mesh.cell_xyz[:, :1], mesh.cell_xyz[:, 1:2]
    h = torch.tensor([500., 1000., 1500.])[None, :]*(1 + .001*x)
    t = torch.tensor([17., 10., 4.])[None, :] + .4*y
    s = torch.tensor([34., 35., 35.5])[None, :] + .05*x
    u = .03*torch.sin(torch.arange(mesh.nEdges)[:, None]*.3 + torch.arange(3)[None, :])
    state = OceanState.from_temperature(u, h, t, s, torch.ones_like(h)[..., None], mesh=mesh, column=column)
    if domain:
        state = domain.project_state(state)
    model = Ocean(mesh, column, domain=domain, dynamics=JMD95Dynamics(domain=domain), stepper=checked_ssprk3)
    return model, state


def test_jmd95_partials_against_existing_eos_and_autograd():
    torch.set_default_dtype(torch.float64)
    t, s, p = [x.requires_grad_() for x in (torch.tensor([-1., 0., 10., 30.]),
        torch.tensor([1., 20., 35., 40.]), torch.tensor([0., 100., 3000., 10000.]))]
    reference = jmd95_seawater_density(s, t, p)
    derivatives = torch.autograd.grad(reference.sum(), (t, s, p))
    rho, *analytic = jmd95_partials(s, t, p)
    torch.testing.assert_close(rho, reference, rtol=8e-16, atol=0)
    for actual, expected in zip(analytic, derivatives):
        torch.testing.assert_close(actual, expected, rtol=2e-14, atol=1e-16)
    # An external MITgcmutils documented check value, not generated by VFS.
    rho = jmd95_partials(torch.tensor(35.5), torch.tensor(3.), torch.tensor(3000.))[0]
    torch.testing.assert_close(rho, torch.tensor(1041.83267), rtol=0, atol=.5e-5)
    zero = jmd95_partials(torch.tensor(0.), torch.tensor(10.), torch.tensor(0.))
    assert all(torch.isfinite(x) for x in zero)


@pytest.mark.parametrize('coast', [False, True])
def test_energy_gradient_and_actual_tendency_work(mesh, coast):
    model, original = case(mesh, coast)
    fields = ('u_e', 'h', 'temp_h', 'salt_h')
    leaves = [getattr(original, name).clone().requires_grad_() for name in fields]
    state = original.with_tensors(*leaves, original.tracer_h)
    gradients = torch.autograd.grad(model.dynamics.total_energy(state), leaves)
    analytic = model.dynamics.energy.gradients(state)
    for name, expected in zip(fields, gradients):
        torch.testing.assert_close(analytic[name], expected, rtol=2e-12, atol=.1)
    rhs = model.tendency(state)
    local = [grad*getattr(rhs, name) for grad, name in zip(gradients, fields)]
    residual, scale = sum(x.sum() for x in local), sum(x.abs().sum() for x in local)
    assert residual.abs() < 512*torch.finfo(state.h.dtype).eps*scale
    # Removing an active pairing term must be detectable, not absorbed by a tolerance.
    bt = analytic['temp_h']/(model.dynamics.rho0*mesh.cell_area[:, None])
    omitted = model.dynamics.centered_trace(mesh, state.temperature())*mesh.grad(bt)
    if coast:
        omitted = model.domain.apply_edge(omitted)
    assert ((gradients[0]*omitted).sum()).abs() > 1e6*residual.abs()
    for name in ('h', 'temp_h', 'salt_h', 'tracer_h'):
        value = getattr(rhs, name)
        area = mesh.cell_area.reshape((-1,) + (1,)*(value.ndim-1))
        local = area*value
        assert local.sum().abs() < 256*torch.finfo(value.dtype).eps*local.abs().sum()
    torch.testing.assert_close(rhs.tracer_h[..., 0], rhs.h, rtol=0, atol=0)


def test_active_T_and_S_and_velocity_independent_pressure(mesh):
    model, state = case(mesh)
    original = model.tendency(state).u_e
    for name in ('temp_h', 'salt_h'):
        fields = {key:getattr(state,key) for key in ('u_e','h','temp_h','salt_h','tracer_h')}
        fields[name] = fields[name] + state.h*.1*mesh.cell_xyz[:, 2:3]
        changed = model.tendency(state.with_tensors(*fields.values())).u_e
        assert (changed-original).abs().max() > 1e-9
    forces = []
    for sign in (-1, 0, 1):
        u = torch.full_like(state.u_e, sign*1e-12)
        changed = state.with_tensors(u, state.h, state.temp_h, state.salt_h, state.tracer_h)
        forces.append(model.dynamics.tendency_terms(changed)['u_e']['hamiltonian_pressure'])
    assert torch.equal(forces[0], forces[2])
    torch.testing.assert_close(forces[1], forces[2], rtol=0, atol=1e-20)


def test_constant_reference_composition_rest_over_topography(mesh):
    bottom = 3000 + 200*mesh.cell_xyz[:, :1]
    column = OceanColumn(3, total_depth=bottom, rest_thickness=torch.tensor([500., 1000., 1500.]))
    h = torch.cat([torch.full_like(bottom,500.), torch.full_like(bottom,1000.), bottom-1500.], -1)
    model = Ocean(mesh,column,dynamics=JMD95Dynamics(),stepper=checked_ssprk3)
    state = model.state(u_e=torch.zeros(mesh.nEdges,3), h=h, temperature=torch.full_like(h,10.), salinity=torch.full_like(h,35.))
    rhs = model.tendency(state)
    assert rhs.u_e.abs().max() < 1e-18
    assert torch.count_nonzero(rhs.h) == 0


def test_checked_step_matches_shared_sequence_and_conserves_inventories(mesh):
    model, state = case(mesh)
    expected = ssprk3(model,state,10.)
    result = model.step(state,10.)
    for name in ('u_e','h','temp_h','salt_h','tracer_h'):
        assert torch.equal(getattr(result,name),getattr(expected,name))
    for name in ('volume','temperature_content','salinity_content','tracer_content'):
        torch.testing.assert_close(model.budgets(state)[name],model.budgets(result)[name],rtol=3e-15,atol=0)


def test_negative_full_euler_stage_is_rejected(mesh):
    model, state = case(mesh)
    # A prescribed tendency isolates the stage policy from spatial/wave stability.
    real_tendency = model.tendency
    def negative_salt(s):
        rhs = real_tendency(s)
        return rhs.with_tensors(torch.zeros_like(s.u_e),torch.zeros_like(s.h),
            torch.zeros_like(s.h),-2*s.salt_h,None if s.tracer_h is None else torch.zeros_like(s.tracer_h))
    model.tendency = negative_salt
    with pytest.raises(FloatingPointError, match='salinity'):
        model.step(state,1.)


def test_one_step_gradient_and_no_forward_autograd(mesh, monkeypatch):
    model, original = case(mesh)
    th = original.temp_h.clone().requires_grad_()
    direction = torch.sin(torch.arange(th.numel()).reshape_as(th)*.7)
    def objective(x):
        state = original.with_tensors(original.u_e,original.h,x,original.salt_h,original.tracer_h)
        return model.step(state,10.).u_e.square().sum()
    grad, = torch.autograd.grad(objective(th),th)
    eps = .01
    fd = (objective(th+eps*direction)-objective(th-eps*direction))/(2*eps)
    torch.testing.assert_close((grad*direction).sum(),fd,rtol=2e-6,atol=1e-12)
    def forbidden(*args,**kwargs):
        raise AssertionError('forward used autograd')
    monkeypatch.setattr(torch.autograd,'grad',forbidden)
    with torch.no_grad():
        result = model.step(original,10.)
    assert torch.isfinite(result.u_e).all()


def test_independent_vertical_integral_and_fixed_content_gradients(mesh):
    import importlib.util
    from pathlib import Path
    path = Path(__file__).parents[2]/'tools/verify_ocean_jmd95.py'
    spec = importlib.util.spec_from_file_location('jmd95_probe',path)
    probe = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(probe)
    _,original = case(mesh)
    h,th,sh = [getattr(original,k).clone().requires_grad_() for k in ('h','temp_h','salt_h')]
    state=original.with_tensors(original.u_e,h,th,sh,original.tracer_h)
    reference=probe.independent_energy(state,order=16)
    expected=torch.autograd.grad(reference,(h,th,sh))
    actual,gradients=JMD95Energy(quadrature_order=8).stratification(state)
    eps=torch.finfo(h.dtype).eps
    assert (actual-reference).abs() < 1024*eps*reference.abs()
    for name,value in zip(('h','temp_h','salt_h'),expected):
        assert (gradients[name]-value).abs().max() < 2048*eps*value.abs().max()
